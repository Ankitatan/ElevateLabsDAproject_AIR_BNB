# ---------------- PREPARE INPUT ----------------
def prepare_input():
    row = {}

    # Fill dataset columns with typical values
    for col in df.columns:
        if col == "price":
            continue

        if pd.api.types.is_numeric_dtype(df[col]):
            row[col] = df[col].median()
        else:
            modes = df[col].mode(dropna=True)
            row[col] = modes.iloc[0] if not modes.empty else ""

    # Replace values entered by the user
    row.update({
        "neighbourhood_group": borough,
        "neighbourhood": neighbourhood,
        "room_type": room_type,
        "latitude": latitude,
        "longitude": longitude,
        "minimum_nights": minimum_nights,
        "number_of_reviews": number_of_reviews,
        "reviews_per_month": reviews_per_month,
        "calculated_host_listings_count": host_listings,
        "availability_365": availability
    })

    # Match model feature names when available
    if hasattr(model, "feature_names_in_"):
        features = list(model.feature_names_in_)
        X = pd.DataFrame([row])

        # Support models trained on one-hot encoded columns
        X = pd.get_dummies(X)

        for col in features:
            if col not in X.columns:
                X[col] = 0

        return X[features]

    # Fallback for models trained on all raw columns
    X = pd.DataFrame([row])
    X = pd.get_dummies(X)

    return X

