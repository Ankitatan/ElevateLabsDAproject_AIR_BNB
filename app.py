import streamlit as st
import pandas as pd
import numpy as np
import joblib
from pathlib import Path

# ---------------- CONFIGURATION ----------------
BASE_DIR = Path(__file__).parent
DATA_PATH = BASE_DIR / "airbnb_eda_cleaned.csv"

MODEL_PATH = BASE_DIR / "airbnb_price_model.joblib"

st.set_page_config(
    page_title="Airbnb Dynamic Pricing Engine",
    page_icon="🏠",
    layout="wide"
)

# ---------------- LOAD FILES ----------------
@st.cache_data
def load_data():
    df = pd.read_csv(DATA_PATH)
    df = df.dropna(subset=["price"])
    return df[df["price"] > 0].copy()

@st.cache_resource
def load_model():
    saved = joblib.load(MODEL_PATH)

    model_obj = saved["model"] if isinstance(saved, dict) else saved

    if isinstance(model_obj, dict):
        st.error(f"Nested model dictionary keys: {list(model_obj.keys())}")
        raise TypeError("The saved model contains a dictionary, not an estimator.")

    if not hasattr(model_obj, "predict"):
        raise TypeError(f"Model has no predict method: {type(model_obj)}")

    features = saved["feature_columns"]
    return model_obj, features

try:
    df = load_data()
    model, feature_columns = load_model()
except Exception as e:
    st.error(f"Could not load dataset or model: {e}")
    st.stop()

# ---------------- HEADER ----------------
st.title("🏠 Airbnb Dynamic Pricing Engine")
st.write(
    "Estimate a listing's nightly price using listing characteristics "
    "and a trained machine-learning model."
)

st.caption("Model estimates are not guaranteed market prices.")

# ---------------- SIDEBAR ----------------
st.sidebar.header("Listing Details")

boroughs = sorted(df["neighbourhood_group"].dropna().unique())
room_types = sorted(df["room_type"].dropna().unique())

borough = st.sidebar.selectbox("Borough", boroughs)
room_type = st.sidebar.selectbox("Room Type", room_types)

borough_data = df[df["neighbourhood_group"] == borough]
neighbourhoods = sorted(borough_data["neighbourhood"].dropna().unique())

neighbourhood = st.sidebar.selectbox(
    "Neighbourhood", neighbourhoods
)

latitude = st.sidebar.number_input(
    "Latitude", min_value=40.4, max_value=41.0,
    value=40.73, format="%.5f"
)

longitude = st.sidebar.number_input(
    "Longitude", min_value=-74.3, max_value=-73.6,
    value=-73.95, format="%.5f"
)

minimum_nights = st.sidebar.number_input(
    "Minimum Nights", min_value=1, max_value=365, value=2
)

number_of_reviews = st.sidebar.number_input(
    "Number of Reviews", min_value=0, value=10
)

reviews_per_month = st.sidebar.number_input(
    "Reviews per Month", min_value=0.0, value=1.0
)

host_listings = st.sidebar.number_input(
    "Host Listings Count", min_value=1, value=1
)

availability = st.sidebar.slider(
    "Availability per Year", 0, 365, 180
)

# ---------------- PREPARE INPUT ----------------

def prepare_input():
    row = {
        "latitude": latitude,
        "longitude": longitude,
        "minimum_nights": minimum_nights,
        "number_of_reviews": number_of_reviews,
        "reviews_per_month": reviews_per_month,
        "calculated_host_listings_count": host_listings,
        "availability_365": availability,
        "neighbourhood_group": borough,
        "neighbourhood": neighbourhood,
        "room_type": room_type
    }

    return pd.DataFrame([row], columns=feature_columns)


# ---------------- TABS ----------------
tab1, tab2, tab3, tab4 = st.tabs([
    "💰 Price Recommendation",
    "📊 Explore Listings",
    "🤖 Model Evaluation",
    "⬇️ Downloads"
])

with tab1:
    st.subheader("Recommended Nightly Price")



    if st.button("Calculate Price", type="primary"):
        try:
            X = prepare_input()

            st.write("Model type:", type(model))
            st.write("Model has predict:", hasattr(model, "predict"))
            st.write("Input columns:", X.columns.tolist())

            prediction = model.predict(X)[0]

            st.success(
                f"Predicted nightly price: ${float(prediction):,.2f}"
            )

        except Exception:
            import traceback
            st.error("Full error traceback:")
            st.code(traceback.format_exc())

        
with tab2:
    st.subheader("Listing Insights")

    filtered = df[df["neighbourhood_group"] == borough]

    col1, col2 = st.columns(2)

    with col1:
        st.write("Median Price by Room Type")
        chart_data = (
            filtered.groupby("room_type")["price"]
            .median().sort_values(ascending=False)
        )
        st.bar_chart(chart_data)

    with col2:
        st.write("Number of Listings by Room Type")
        st.bar_chart(filtered["room_type"].value_counts())

    st.write("Listing Locations")
    st.map(filtered[["latitude", "longitude"]].dropna().sample(
        min(1000, len(filtered)), random_state=42
    ) if len(filtered) else pd.DataFrame(columns=["latitude", "longitude"]))

    st.write("Dataset Preview")
    st.dataframe(filtered.head(100), use_container_width=True)

with tab3:
    st.subheader("Model Evaluation")

    metrics_path = BASE_DIR / "airbnb_model_output" / "model_metrics.txt"

    if metrics_path.exists():
        st.code(metrics_path.read_text(encoding="utf-8"))
    else:
        st.warning("Model metrics file not found.")

    st.write("Dataset Statistics")
    col1, col2, col3 = st.columns(3)
    col1.metric("Valid Listings", f"{len(df):,}")
    col2.metric("Median Price", f"${df['price'].median():,.2f}")
    col3.metric("Mean Price", f"${df['price'].mean():,.2f}")

    st.caption(
        "Previous evaluation: MAE $55.78, RMSE $177.25, R² 0.2153. "
        "These metrics apply only if this is the same trained model and test set."
    )

with tab4:
    st.subheader("Download Project Data")

    st.download_button(
        "Download Cleaned Listings",
        df.to_csv(index=False),
        "airbnb_cleaned_listings.csv",
        "text/csv"
    )

    predictions_path = (
        BASE_DIR / "airbnb_model_output" / "airbnb_test_predictions.csv"
    )

    if predictions_path.exists():
        predictions = pd.read_csv(predictions_path)

        st.download_button(
            "Download Test Predictions",
            predictions.to_csv(index=False),
            "airbnb_test_predictions.csv",
            "text/csv"
        )

st.divider()
st.caption("Airbnb Dynamic Pricing Recommendation Engine | Python • Pandas • Scikit-learn • Streamlit")