@st.cache_resource
def load_model():
    saved = joblib.load(MODEL_PATH)

    features = saved["feature_columns"]

    def find_estimator(obj, depth=0):
        if depth > 5:
            return None

        if hasattr(obj, "predict") and callable(obj.predict):
            return obj

        if isinstance(obj, dict):
            for value in obj.values():
                found = find_estimator(value, depth + 1)
                if found is not None:
                    return found

        if isinstance(obj, (tuple, list)):
            for value in obj:
                found = find_estimator(value, depth + 1)
                if found is not None:
                    return found

        return None

    model_obj = find_estimator(saved)

    if model_obj is None:
        raise TypeError(
            f"No prediction model found. Saved object type: {type(saved)}"
        )

    return model_obj, features


